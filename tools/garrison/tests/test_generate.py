import re
from pathlib import Path

import pytest

from garrison import generate
from ra2data import ini

FIXTURES = Path(__file__).parent / "fixtures"
REPO_ROOT = Path(__file__).resolve().parents[3]


@pytest.fixture
def sample():
    return (ini.parse_ini(str(FIXTURES / "rules.ini")), ini.parse_ini(str(FIXTURES / "art.ini")))


def test_load_garrisonables_reads_capacity_and_ports(sample):
    found = {g.id: g for g in generate.load_garrisonables(*sample)}
    assert sorted(found) == ["CAFAKE01", "CAFAKE02"]
    assert found["CAFAKE01"].capacity == 3
    assert found["CAFAKE01"].ports[:2] == [(60, 0), (-30, 15)]
    # Image= redirects the art lookup
    assert found["CAFAKE02"].ports[0] == (0, 15)


def test_can_be_occupied_is_case_insensitive():
    rules = {f"CA{i}": {"CanBeOccupied": v, "MaxNumberOccupants": "1"} for i, v in enumerate(["yes", "Yes", "TRUE", "1", "no", "0"])}
    assert [g.id for g in generate.load_garrisonables(rules, {})] == ["CA0", "CA1", "CA2", "CA3"]


def test_pixel_to_wvec_origin_and_axes():
    assert generate.pixel_to_wvec(0, 0) == (0, 0, 0)
    # one cell along world +x is (+30,+15) px; along world +y is (-30,+15) px
    assert generate.pixel_to_wvec(30, 15) == (1024, 0, 0)
    assert generate.pixel_to_wvec(-30, 15) == (0, 1024, 0)
    # a pure +x pixel offset lies on the x/y diagonal: +x and -y in equal measure
    x, y, z = generate.pixel_to_wvec(60, 0)
    assert x == -y > 0 and z == 0


def test_missing_ports_get_defaults(sample):
    ports = {g.id: g for g in generate.load_garrisonables(*sample)}
    # CAFAKE01 has no MuzzleFlash2, CAFAKE02's MuzzleFlash1 is malformed
    assert ports["CAFAKE01"].ports[2] == generate._default_ports(3)[2]
    assert ports["CAFAKE02"].ports[1] == generate._default_ports(2)[1]
    art_less = generate.load_garrisonables({"CAX": {"CanBeOccupied": "yes", "MaxNumberOccupants": "4"}}, {})
    assert len(art_less[0].ports) == 4
    assert len(set(art_less[0].ports)) == 4


def test_generator_deterministic(sample):
    first = generate.render(generate.load_garrisonables(*sample))
    second = generate.render(generate.load_garrisonables(*reversed_sections(sample)))
    assert first == second
    assert first.startswith("# DO NOT EDIT - generated by tools/garrison/generate.py")
    assert "\ncafake01:\n\tCargo@GARRISON:" in first
    assert "PortCones: 88, 88, 88" in first
    assert "\r" not in first


def reversed_sections(sample):
    rules, art = sample
    return dict(reversed(list(rules.items()))), art


def test_real_rules_has_120_garrisonables(ra2ini):
    folder = ini.ra2ini_dir()
    art = ini.parse_ini(str(folder / generate.ART_FILE))
    found = generate.load_garrisonables(ra2ini, art)
    assert len(found) == 120
    for g in found:
        assert len(g.ports) == g.capacity


def test_committed_garrison_yaml_is_current(ra2ini):
    folder = ini.ra2ini_dir()
    art = ini.parse_ini(str(folder / generate.ART_FILE))
    expected = generate.render(generate.load_garrisonables(ra2ini, art))
    assert generate.DEFAULT_OUT.read_text(encoding="utf-8") == expected


def test_garrison_yaml_registered_after_civilian_structures():
    mod = (REPO_ROOT / "mods" / "ra2" / "mod.yaml").read_text(encoding="utf-8")
    assert mod.index("ra2|rules/civilian-structures.yaml") < mod.index("ra2|rules/garrison.yaml")


@pytest.mark.integration
def test_garrison_buildings_stay_neutral_and_uncapturable():
    from ra2data.resolved import resolve_actor

    names = re.findall(r"^([a-z0-9_]+):$", generate.DEFAULT_OUT.read_text(encoding="utf-8"), re.M)
    assert len(names) == 120
    forbidden = ("Capturable", "MustBeDestroyed", "UpdatesPlayerStatistics")
    for name in names:
        rules = resolve_actor(name)
        for trait in rules:
            assert trait.split("@")[0] not in forbidden, f"{name} has {trait}"
        assert "Cargo@GARRISON" in rules and "GarrisonOwnership@GARRISON" in rules, name
