def _covers_full_circle(yaws, cones):
    # AttackGarrisoned: a port can fire at a facing when min(left turn, right turn) <= cone
    def within(angle, yaw, cone):
        delta = (angle - yaw) % 1024
        return min(delta, 1024 - delta) <= cone
    return all(any(within(a, y, c) for y, c in zip(yaws, cones)) for a in range(1024))


def test_covers_full_circle_helper():
    assert _covers_full_circle([0, 512], [256, 256])
    assert not _covers_full_circle([0, 512], [200, 200])


def test_committed_port_cones_cover_full_circle():
    text = generate.DEFAULT_OUT.read_text(encoding="utf-8")
    yaws = re.findall(r"^\t\tPortYaws: (.*)$", text, re.M)
    cones = re.findall(r"^\t\tPortCones: (.*)$", text, re.M)
    assert len(yaws) == len(cones) == 120
    for y, c in zip(yaws, cones):
        assert _covers_full_circle([int(v) for v in y.split(",")], [int(v) for v in c.split(",")]), y


def reversed_sections(sample):
    rules, art = sample
    return dict(reversed(list(rules.items()))), art


