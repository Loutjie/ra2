"""Generate mods/ra2/rules/garrison.yaml from RA2's rules.ini and art.ini.

Usage: python3 -m garrison.generate [--rules RULES.ini] [--art ART.ini] [--out FILE]
(run from the tools/ directory; defaults to the base RA2 INI files and
mods/ra2/rules/garrison.yaml).
"""
from __future__ import annotations

import argparse
import math
import sys
from dataclasses import dataclass
from pathlib import Path

from ra2data import ini

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "mods" / "ra2" / "rules" / "garrison.yaml"
ART_FILE = "ra2.mix__local.mix__art.ini"

HEADER = (
    "# DO NOT EDIT - generated by tools/garrison/generate.py from rules.ini/art.ini.\n"
    "# Re-run the generator instead of changing this file by hand.\n"
)

TRUE_VALUES = ("yes", "true", "1")
PORT_HEIGHT = 128  # WDist above the building's origin; matches the old hand-written cawsh12 ports
PORT_CONE = 512  # WAngle half-angle: RA2 occupants fire in every direction, the ports only place muzzle flashes
DEFAULT_PORT_RADIUS_PX = 24  # horizontal screen radius (px) of the fallback ring of ports


@dataclass(frozen=True)
class Garrisonable:
    id: str
    capacity: int
    ports: list  # list[tuple[int, int]] of RA2 screen-pixel offsets from the building centre


def pixel_to_world(x: int, y: int) -> tuple[int, int]:
    """Convert an RA2 screen-pixel offset (x right, y down) to a world (u, v) vector.

    This mod uses a RectangularIsometric grid (60x30 px cells). Map.CenterOfCell
    places cell (cx, cy) at WPos(724*(cx-cy+1), 724*(cx+cy+1)), so world axes are
    screen-aligned (u right, v down) and one cell step of (+30, +15) px is
    (724, 724) WDist (724 = 512*sqrt(2); 1024 is the length along a cell axis).
    Hence u = x*724/30 and v = y*724/15, rounded half up.
    """
    return (_round_div(x * 724, 30), _round_div(y * 724, 15))


def pixel_to_wvec(x: int, y: int) -> tuple[int, int, int]:
    """Convert an RA2 screen-pixel offset to the LOCAL WVec used by PortOffsets.

    AttackGarrisoned applies BodyOrientation.LocalToWorld to port offsets. With
    UseClassicPerspectiveFudge: false (defaults.yaml) that is world = (local.Y,
    -local.X), so local = (-v, u) where (u, v) = pixel_to_world(x, y). A pure
    screen-down pixel offset therefore has negative local x and zero local y.
    z is 0.
    """
    u, v = pixel_to_world(x, y)
    return (-v, u, 0)


def _round_div(n: int, d: int) -> int:
    return (2 * n + d) // (2 * d)


def yaw_of_world(u: int, v: int) -> int:
    """Engine yaw (WVec.Yaw: ArcTan(-v, u) - 256, 1024 per turn) of a world vector.

    OpenRA north is -v: north is 0, west 256, south 512, east 768. Zero vector gives 0.
    """
    if u == 0 and v == 0:
        return 0
    return (round(math.atan2(-v, u) * 1024 / (2 * math.pi)) - 256) % 1024


def _default_ports(capacity: int) -> list:
    """Evenly spaced ring of screen-pixel offsets (a ground circle seen at 2:1), used
    when art.ini has no MuzzleFlashN."""
    ports = []
    for i in range(capacity):
        angle = 2 * math.pi * i / capacity
        ports.append((round(DEFAULT_PORT_RADIUS_PX * math.cos(angle)), round(DEFAULT_PORT_RADIUS_PX * math.sin(angle) / 2)))
    return ports


def _parse_pixels(value: str):
    parts = value.split(",")
    if len(parts) != 2:
        return None
    try:
        return int(parts[0]), int(parts[1])
    except ValueError:
        return None


def load_garrisonables(rules, art) -> list:
    """Garrisonable buildings: sections with CanBeOccupied=yes and MaxNumberOccupants > 0.

    Ports come from art.ini MuzzleFlash0..N-1 (N = capacity); missing or malformed
    entries get a default evenly spaced position. The result is sorted by id.

    The flag is parsed case-insensitively like RA2 does (yes/true/1): the original
    rules.ini has one building (CAMEX02) written as "Yes".
    """
    result = []
    for name, section in rules.items():
        if section.get("CanBeOccupied", "").lower() not in TRUE_VALUES:
            continue
        try:
            capacity = int(section.get("MaxNumberOccupants", "0"))
        except ValueError:
            continue
        if capacity <= 0:
            continue
        art_section = art.get(section.get("Image", name), art.get(name, {}))
        defaults = _default_ports(capacity)
        ports = []
        for i in range(capacity):
            parsed = _parse_pixels(art_section.get(f"MuzzleFlash{i}", ""))
            ports.append(parsed if parsed is not None else defaults[i])
        result.append(Garrisonable(name, capacity, ports))
    return sorted(result, key=lambda g: g.id)


def render(garrisonables) -> str:
    out = [HEADER]
    for g in garrisonables:
        offsets = [(lx, ly, PORT_HEIGHT) for lx, ly, _ in (pixel_to_wvec(x, y) for x, y in g.ports)]
        yaws = [yaw_of_world(*pixel_to_world(x, y)) for x, y in g.ports]
        out.append(
            f"\n{g.id.lower()}:\n"
            "\tCargo@GARRISON:\n"
            "\t\tTypes: Garrisoner\n"
            f"\t\tMaxWeight: {g.capacity}\n"
            "\t\tLoadedCondition: garrisoned\n"
            # GarrisonOwnership ejects the occupants over the footprint instead: the engine drops them all
            # into the origin cell, which only has room for three infantry.
            "\t\tEjectOnDeath: false\n"
            "\tAttackGarrisoned@GARRISON:\n"
            "\t\tArmaments: garrison\n"
            f"\t\tPortOffsets: {', '.join(f'{x},{y},{z}' for x, y, z in offsets)}\n"
            f"\t\tPortYaws: {', '.join(map(str, yaws))}\n"
            f"\t\tPortCones: {', '.join([str(PORT_CONE)] * len(offsets))}\n"
            "\tWithCargoPipsDecoration@GARRISON:\n"
            "\t\tPosition: BottomLeft\n"
            # Always shown while occupied: civilian buildings use the terrain palette and do not take the owner's colour.
            "\t\tRequiresCondition: garrisoned\n"
            "\t\tPalette: pips\n"
            "\t\tCustomPipSequences:\n"
            "\t\t\tblue: pip-blue\n"
            "\t\t\tyellow: pip-yellow\n"
            "\t\t\tgreen: pip-green\n"
            "\t\t\tred: pip-red\n"
            # AttackFollow only acquires targets through AutoTarget; empty buildings must not scan.
            "\tAutoTarget@GARRISON:\n"
            "\t\tRequiresCondition: garrisoned\n"
            "\tAutoTargetPriority@GARRISON:\n"
            "\t\tRequiresCondition: garrisoned\n"
            "\t\tValidTargets: Infantry, Vehicle, Water, Underwater, Defense\n"
            "\t\tInvalidTargets: NoAutoTarget, WaterStructure\n"
            # Civilian buildings have no Valued, so repairing would cost max(1, 0) credits.
            "\t-RepairableBuilding:\n"
            "\t-WithBuildingRepairDecoration:\n"
            "\tGarrisonOwnership@GARRISON:\n"
        )
    return "".join(out)


def main(argv=None) -> int:
    folder = ini.ra2ini_dir()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rules", default=str(folder / ini.RULES_FILE) if folder else None)
    parser.add_argument("--art", default=str(folder / ART_FILE) if folder else None)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args(argv)
    if not args.rules or not args.art:
        print("original INI files not found; pass --rules/--art or set $RA2INI", file=sys.stderr)
        return 1
    text = render(load_garrisonables(ini.parse_ini(args.rules), ini.parse_ini(args.art)))
    Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
