"""Generate the Exact balance files from the base RA2 rules.ini and the mod's resolved rules.

Writes (paths relative to the repository root):
  mods/ra2/rules/exact/actors.yaml       twin actors `<id>.exact` (exact.actors.render_twin)
  mods/ra2/rules/exact/reimagined.yaml   the overlay limiting base actors to Reimagined
  mods/ra2/rules/exact/globals.yaml      RA2's global and special rules on the twins, and the
                                         Exact/Reimagined trait pairs of the neutral tech
                                         buildings (exact.globals)
  mods/ra2/weapons/exact/weapons.yaml    twin weapons `<weapon>.exact` for every weapon a twin's
                                         Armament names, with the RA2 weapon values
                                         (exact.weapons, which documents the mapping and the
                                         exceptions that stay `Inherits: <weapon>` stubs)
  tools/exact/weapon_exceptions.json     those exceptions, the RA2 weapons without a mod
                                         counterpart and the projectile speed notes
  mods/ra2/rules/exact/EXCEPTIONS.md     every conversion exception (exact.exceptions) with
                                         its reason and what it affected
  mods/ra2/rules/exact/ai.yaml           the AI bot modules' actor lists (mods/ra2/rules/ai.yaml)
                                         with each twin beside its base, and support power
                                         decisions for Exact powers with another OrderName
                                         (exact.ai)

Conversion exceptions
  All twins are computed first; then every rule of exact.exceptions.EXCEPTIONS adjusts them
  (actor trait overrides and weapon twins), and only then are the files rendered.

Which actors get a twin
  Every RA2 player-buildable (exact.model.load_actors) whose lowercased ID is a buildable
  actor of the mod, plus the RA2 actors they deploy into or undeploy from (the construction
  yards, which RA2 does not list as buildable). Mod buildables that RA2 defines but cannot
  build (ghost) are not twinned and become Reimagined only; mod buildables without any RA2
  section stay buildable in both modes; RA2 buildables without a mod actor are not
  generated. These lists, and RA2 values with no trait to go to, head actors.yaml.

Untwinned actors (buildable or not, e.g. hornet, civilian vehicles) get the twins of their
twinned repair/rearm hosts appended in reimagined.yaml (exact.actors.appended_twins).

The base actors are read from the built mod (ra2data.resolved). A tree read back after a
previous run already carries the overlay; exact.snapshot.strip_ignored removes it, so the
output does not depend on whether the overlay is loaded: two runs give identical bytes.

CLI (run from the tools/ directory, or anywhere with tools/ on PYTHONPATH; needs a built mod):
    python3 -m exact.generate          # regenerate the files
    python3 -m exact.generate --check  # exit 1 if a committed file is out of date
The rules.ini folder is $RA2INI or ~/Projects/ra2-reference/ini (ra2data.ini.ra2ini_dir).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Collection, Mapping
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from exact import ai, actors, exceptions, globals as exact_globals, weapons as twin_weapons
from exact.model import load_actor, load_actors
from exact.snapshot import (HOST_FIELDS, NEUTRAL_TECH_ACTORS, RULES_DIR, _blocks, actor_names,
    has_buildable, strip_ignored, twinned_actors, weapon_definitions)
from ra2data import ini
from ra2data.resolved import REPO_ROOT, parse_miniyaml, resolve_actor, resolve_weapon

HEADER = "# GENERATED by tools/exact/generate.py from rules.ini — do not edit\n"
ACTORS_FILE = "mods/ra2/rules/exact/actors.yaml"
OVERLAY_FILE = "mods/ra2/rules/exact/reimagined.yaml"
GLOBALS_FILE = "mods/ra2/rules/exact/globals.yaml"
WEAPONS_FILE = "mods/ra2/weapons/exact/weapons.yaml"
WEAPON_EXCEPTIONS_FILE = "tools/exact/weapon_exceptions.json"
AI_FILE = "mods/ra2/rules/exact/ai.yaml"


def ra2_actors(rules: dict) -> dict:
    """Lowercase ID -> ExactActor: the buildables plus what they deploy into or undeploy from."""
    found = {a.id.lower(): a for a in load_actors(rules)}
    pending = list(found.values())
    while pending:
        actor = pending.pop()
        for key in ("DeploysInto", "UndeploysInto"):
            target = actor.raw.get(key, "").strip()
            if target and target.lower() not in found:
                loaded = load_actor(rules, target)
                if loaded is not None:
                    found[target.lower()] = loaded
                    pending.append(loaded)
    return found


def neutral_parents(names, rules_dir: Path = RULES_DIR) -> dict[str, str]:
    """Neutral building -> the one of `names` its rules block inherits (it gets that one's pairs)."""
    blocks = _blocks(rules_dir)
    out = {}
    for name in names:
        for parent in re.findall(r"^\s*Inherits(?:@\w+)?:\s*(\S+)\s*$", blocks.get(name, ""), re.M):
            if parent in names:
                out[name] = parent
    return out


def twin_inheritors(twins: Collection[str], no_replace: Collection[str] = (),
        blocks: Mapping[str, str] | None = None) -> set[str]:
    """Untwinned non-abstract actors that inherit `ReplaceOnPrerequisite@BALANCE` from a twinned
    actor (one of `twins` not in `no_replace`), directly or through abstract (`^`) templates.
    An untwinned non-abstract parent removes the trait itself, so it passes nothing on.
    blocks: raw rules text per top-level node (default: the mod's rule files, snapshot._blocks)."""
    if blocks is None:
        blocks = _blocks(RULES_DIR)
    replaced = set(twins) - set(no_replace)

    def parents(name: str) -> list[str]:
        return [p.strip() for p in re.findall(r"^\s*Inherits(?:@\w+)?:\s*(\S+)\s*$", blocks.get(name, ""), re.M)]

    def carries(name: str, seen: frozenset = frozenset()) -> bool:
        if name in replaced:
            return True
        return name.startswith("^") and any(p not in seen and carries(p, seen | {name}) for p in parents(name))

    return {n for n in blocks if n[0] not in "^-@" and n not in twins and any(carries(p) for p in parents(n))}


def _comment(title: str, names) -> str:
    return f"# {title}: {', '.join(names) if names else '(none)'}\n"


def build(rules: dict, base_actors: dict, weapons: dict[str, str],
        host_actors: dict | None = None, resolve_base_weapon=resolve_weapon,
        neutral_actors: dict | None = None, ai_source: dict | None = None,
        rules_blocks: Mapping[str, str] | None = None) -> dict[str, str]:
    """Generated file path (relative to the repository root) -> contents.

    rules: parsed rules.ini. base_actors: mod buildable ID -> resolved tree.
    weapons: lowercase weapon name -> defined weapon name.
    host_actors: other actors (not buildable) that have repair/rearm host lists -> resolved tree.
    resolve_base_weapon: mod weapon name -> resolved tree (default: the built mod).
    neutral_actors: neutral tech building -> resolved tree without GLOBALS_FILE
    (resolve_neutral_actors).
    ai_source: parsed AI rules (default: the mod's ai.yaml, exact.ai.AI_SOURCE).
    rules_blocks: raw rules text per top-level node, for twin_inheritors (default: the mod's files).
    """
    ra2 = ra2_actors(rules)
    twins = sorted(set(ra2) & set(base_actors))
    # Strip names appended by this run's twins and by the previous run's (the committed file).
    strip_twins = set(twins) | twinned_actors()
    bases = {name: strip_ignored(tree, strip_twins) for name, tree in base_actors.items()}
    hosts = {name: strip_ignored(tree, strip_twins) for name, tree in (host_actors or {}).items()
        if name not in bases}
    children = actors.spawned_children(bases)

    notes: list[str] = []
    stubs: set[str] = set()
    twin_traits: dict[str, dict[str, dict[str, str]]] = {}
    for name in twins:
        traits, twin_notes = actors.twin_traits(ra2[name], bases[name], twins=twins, weapons=weapons)
        twin_traits[name] = traits
        notes += twin_notes
        stubs.update(t["Weapon"][: -len(actors.SUFFIX)] for k, t in traits.items()
            if actors.trait_type(k) == "Armament" and "Weapon" in t)

    # Global rules; the death and Lightning Storm weapons they name get twins too.
    neutral = dict(neutral_actors or {})
    rules_globals = exact_globals.build_globals(rules, ra2, bases, twins, neutral, weapons, stubs,
        neutral_parents(neutral))
    stubs.update(rules_globals.weapons)

    # Weapon twins first, then the exception rules (which also adjust twin_traits).
    generated = exceptions.Generated(rules, {n: bases[n] for n in twins}, twin_traits, {},
        resolve_base_weapon)
    applied: dict[str, list[str]] = {}

    def adjust(weapon_twins: dict) -> None:
        generated.weapons = weapon_twins
        filled = exact_globals.fill_weather_weapons(rules_globals, rules, weapon_twins, resolve_base_weapon)
        if filled:
            rules_globals.notes.setdefault("lightning-storm", []).extend(filled)
        applied.update(exceptions.apply(generated))

    weapons_body, weapons_report = twin_weapons.render_weapons(rules, stubs, [ra2[n] for n in twins],
        resolve_base_weapon, adjust=adjust)
    # globals.yaml loads after actors.yaml: where it sets or removes SpawnSurvivors, the
    # rewritten list in actors.yaml would be a dead duplicate.
    for name in twins:
        owned = rules_globals.blocks.get(actors.twin_name(name), {})
        if "SpawnSurvivors" in owned or "-SpawnSurvivors" in owned:
            twin_traits[name].pop("SpawnSurvivors", None)
    blocks = [actors.render_twin(ra2[name], bases[name], twins=twins, weapons=weapons,
        replaced=name not in children, traits=twin_traits[name]) for name in twins]

    # RA2 defines these but cannot build them: Reimagined only. Without an RA2 section: both modes.
    reimagined_only = sorted(n for n in set(bases) - set(ra2) if load_actor(rules, n) is not None)
    both_modes = sorted(set(bases) - set(ra2) - set(reimagined_only))
    missing = sorted(a.id for key, a in ra2.items() if key not in bases)
    actors_text = (HEADER
        + _comment("Mod buildables without a twin, Reimagined only (RA2 cannot build them)", reimagined_only)
        + _comment("Mod buildables without an RA2 counterpart (available in both modes)", both_modes)
        + _comment("RA2 buildables without a mod actor (not generated)", missing)
        + "".join(f"# Not applied: {note}\n" for note in sorted(notes))
        + "\n" + "\n".join(blocks))
    overlay_text = HEADER + "\n" + actors.render_reimagined_overlay({**hosts, **bases}, twins=twins,
        no_replace=children, reimagined_only=reimagined_only,
        inheritors=twin_inheritors(twins, children, rules_blocks))
    weapons_text = HEADER + weapons_body
    globals_text = HEADER + "\n" + exact_globals.render_globals(rules_globals)
    generated_rules: dict[str, dict] = {}
    for text in (actors_text, globals_text):
        for name, traits in parse_miniyaml(text).items():
            generated_rules.setdefault(name, {}).update(traits)
    if ai_source is None:
        ai_source = parse_miniyaml((REPO_ROOT / ai.AI_SOURCE).read_text(encoding="utf-8"))
    ai_body = ai.render_ai(ai_source, twins, ai.renamed_orders(generated_rules, bases))
    ai_text = HEADER + ("\n" + ai_body if ai_body else "")
    report_text = json.dumps({"generated": HEADER[2:].strip(), **weapons_report}, indent="\t",
        ensure_ascii=False) + "\n"
    buildable = {a.id.lower() for a in load_actors(rules)}
    facts = {**weapons_report, "twins": twins, "dropped": sorted(notes),
        "deploy_added": [f"{n}{actors.SUFFIX} (RA2 {ra2[n].id})" for n in twins if n not in buildable],
        "reimagined_only": reimagined_only, "both_modes": both_modes, "missing": missing,
        "globals": rules_globals.notes,
        "exact_host_users": sorted(n for n, tree in {**hosts, **bases}.items()
            if n not in twins and actors.appended_host_fields(tree, twins)),
        "generated_weapons": sorted(t.twin for t in generated.weapons.values() if t.values is not None),
        "point_spread": sorted(t.twin for t in generated.weapons.values() if t.values is not None
            and any(isinstance(v, dict) and v.get("Spread") == twin_weapons.POINT_SPREAD
                for v in t.values.values()))}
    return {ACTORS_FILE: actors_text, OVERLAY_FILE: overlay_text, GLOBALS_FILE: globals_text,
        WEAPONS_FILE: weapons_text,
        WEAPON_EXCEPTIONS_FILE: report_text, AI_FILE: ai_text,
        exceptions.REPORT_FILE: exceptions.render_report(HEADER, facts, applied)}


def resolve_all(names: list[str]) -> dict[str, dict]:
    with ThreadPoolExecutor(max_workers=8) as pool:
        return dict(zip(names, pool.map(resolve_actor, names)))


def resolve_base_actors() -> dict[str, dict]:
    """Resolved tree of every buildable actor of the mod (needs a built mod)."""
    return {name: tree for name, tree in resolve_all(actor_names()).items() if has_buildable(tree)}


def resolve_host_actors() -> dict[str, dict]:
    """Resolved tree of every non-buildable actor with a repair/rearm host list (needs a built mod)."""
    fields = "|".join(sorted(set(HOST_FIELDS.values())))
    trees = resolve_all(actor_names(field=fields))
    return {name: tree for name, tree in trees.items() if not has_buildable(tree)
        and any(actors.trait_type(k) in HOST_FIELDS for k in tree)}


# GLOBALS_FILE as listed in mod.yaml's Rules (relative to the mod folder).
GLOBALS_RULES_ENTRY = GLOBALS_FILE.removeprefix("mods/ra2/")


def resolve_neutral_actors() -> dict[str, dict]:
    """Resolved tree of every neutral tech building (exact.snapshot.NEUTRAL_TECH_ACTORS) as the
    mod's own rule files define it, without GLOBALS_FILE: the Reimagined side of each pair is
    copied from these trees, so an edit of the source files must reach it (a tree read back with
    the previous pairs would keep the previous copy)."""
    names = list(NEUTRAL_TECH_ACTORS)
    with ThreadPoolExecutor(max_workers=8) as pool:
        return dict(zip(names, pool.map(lambda n: resolve_actor(n, without=(GLOBALS_RULES_ENTRY,)), names)))


def load_rules() -> dict:
    folder = ini.ra2ini_dir()
    if folder is None or not (folder / ini.RULES_FILE).is_file():
        raise SystemExit(f"{ini.RULES_FILE} not found (set $RA2INI)")
    return ini.parse_ini(str(folder / ini.RULES_FILE))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report out-of-date files instead of writing")
    args = parser.parse_args(argv)
    outputs = build(load_rules(), resolve_base_actors(), weapon_definitions(), resolve_host_actors(),
        neutral_actors=resolve_neutral_actors())
    stale = []
    for rel, text in outputs.items():
        path = REPO_ROOT / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        stale.append(rel)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    verb = "out of date" if args.check else "written"
    print(f"{len(stale)} file(s) {verb}" + "".join(f"\n  {rel}" for rel in stale))
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
