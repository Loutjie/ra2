import re
from pathlib import Path

from damagefires import generate
from garrison.generate import pixel_to_wvec
from ra2data import ini
from ra2data.resolved import parse_miniyaml

REPO_ROOT = Path(__file__).resolve().parents[3]

# Fictional sample data
RULES = {
    "GAFAKE": {},
    "NAFAKE": {"Image": "NAFAKEART"},
    "CAMISSING": {},
    "NOTINMOD": {},
}
ART = {
    "GAFAKE": {"DamageFireOffset0": "-20,32", "DamageFireOffset1": "3,12", "DamageFireOffset3": "9,9"},
    "NAFAKE": {"DamageFireOffset0": "1,1"},
    "NAFAKEART": {"DamageFireOffset0": "30,-15", "DamageFireOffset1": "oops", "DamageFireOffset2": "0,15"},
    "CAMISSING": {},
    "NOTINMOD": {"DamageFireOffset0": "5,5"},
}
ACTORS = {"gafake", "nafake", "camissing"}


def test_load_fires_reads_offsets_in_order_until_the_first_missing_index():
    fires = dict(generate.load_fires(RULES, ART, ACTORS))
    # DamageFireOffset2 is missing, so the stray DamageFireOffset3 is not read (RA2 stops there too)
    assert fires["GAFAKE"] == [(-20, 32), (3, 12)]


def test_load_fires_follows_image_and_skips_malformed_offsets():
    fires = dict(generate.load_fires(RULES, ART, ACTORS))
    assert fires["NAFAKE"] == [(30, -15), (0, 15)]


def test_load_fires_reads_keys_case_insensitively_like_ra2():
    # The original art.ini spells one key "damageFireOffset1" (CAPARS12, the Eiffel Tower).
    art = {"GAX": {"DamageFireOffset0": "1,2", "damageFireOffset1": "3,4", "DAMAGEFIREOFFSET2": "5,6"}}
    assert dict(generate.load_fires({"GAX": {}}, art, {"gax"}))["GAX"] == [(1, 2), (3, 4), (5, 6)]


def test_load_fires_reads_image_case_insensitively():
    art = {"GAXART": {"DamageFireOffset0": "1,2"}}
    assert dict(generate.load_fires({"GAX": {"image": "GAXART"}}, art, {"gax"}))["GAX"] == [(1, 2)]


def test_main_never_reads_the_committed_output_as_an_actor_source(tmp_path, monkeypatch):
    seen = {}
    def fake_names(rules_dir, exclude=None):
        seen["exclude"] = exclude
        return set()

    monkeypatch.setattr(generate, "mod_actor_names", fake_names)
    rules = tmp_path / "rules.ini"
    art = tmp_path / "art.ini"
    rules.write_text("[GAX]\n", encoding="latin-1")
    art.write_text("[GAX]\n", encoding="latin-1")
    assert generate.main(["--rules", str(rules), "--art", str(art), "--out", str(tmp_path / "out.yaml")]) == 0
    assert seen["exclude"] == generate.DEFAULT_OUT


def test_load_fires_only_lists_mod_actors_with_fires():
    assert [name for name, _ in generate.load_fires(RULES, ART, ACTORS)] == ["GAFAKE", "NAFAKE"]


def test_render_adds_one_overlay_per_fire_shown_only_when_heavily_damaged():
    actors = parse_miniyaml(generate.render(generate.load_fires(RULES, ART, ACTORS)))
    gafake = actors["gafake"]
    assert sorted(gafake) == ["GrantConditionOnDamageState@HEAVYDAMAGE", "WithIdleOverlay@DAMAGEFIRE0", "WithIdleOverlay@DAMAGEFIRE1"]
    grant = gafake["GrantConditionOnDamageState@HEAVYDAMAGE"]
    assert grant["Condition"] == generate.CONDITION
    # The engine's Heavy state starts below 50%, RA2's ConditionYellow
    assert grant["ValidDamageStates"] == "Heavy, Critical"
    for i, image in enumerate(["largefire", "mediumfire"]):
        fire = gafake[f"WithIdleOverlay@DAMAGEFIRE{i}"]
        assert fire["RequiresCondition"] == generate.CONDITION
        assert fire["Image"] == image
        assert fire["Sequence"] == "idle"
        assert fire["Palette"] == "effect"
    x, y, _ = pixel_to_wvec(-20, 32)
    assert gafake["WithIdleOverlay@DAMAGEFIRE0"]["Offset"] == f"{x},{y},{generate.FIRE_HEIGHT}"


def test_render_cycles_the_three_fire_types():
    rules = {"GAX": {}}
    art = {"GAX": {f"DamageFireOffset{i}": "0,0" for i in range(4)}}
    gax = parse_miniyaml(generate.render(generate.load_fires(rules, art, {"gax"})))["gax"]
    images = [gax[f"WithIdleOverlay@DAMAGEFIRE{i}"]["Image"] for i in range(4)]
    assert images == ["largefire", "mediumfire", "smallfire", "largefire"]


def test_render_is_deterministic_and_marked_generated():
    first = generate.render(generate.load_fires(RULES, ART, ACTORS))
    reversed_rules = dict(reversed(list(RULES.items())))
    assert first == generate.render(generate.load_fires(reversed_rules, ART, ACTORS))
    assert first.startswith("# DO NOT EDIT - generated by tools/damagefires/generate.py")
    assert "\r" not in first


def test_mod_actor_names_reads_top_level_actors_but_not_templates_or_the_output(tmp_path):
    (tmp_path / "a.yaml").write_text("^Template:\n\tFoo:\ngapowr:\n\tBar:\n# comment\nnapowr:\n", encoding="utf-8")
    (tmp_path / "out.yaml").write_text("ghost:\n", encoding="utf-8")
    assert generate.mod_actor_names(tmp_path, exclude=tmp_path / "out.yaml") == {"gapowr", "napowr"}


def test_damage_fires_yaml_is_listed_before_garrison_yaml():
    mod = (REPO_ROOT / "mods" / "ra2" / "mod.yaml").read_text(encoding="utf-8")
    rules = re.findall(r"^\tra2\|rules/(\S+)$", mod, re.M)
    assert rules[-2:] == ["damage-fires.yaml", "garrison.yaml"]


def test_committed_damage_fires_yaml_is_current(ra2ini):
    folder = ini.ra2ini_dir()
    art = ini.parse_ini(str(folder / generate.ART_FILE))
    actors = generate.mod_actor_names(generate.DEFAULT_OUT.parent, exclude=generate.DEFAULT_OUT)
    expected = generate.render(generate.load_fires(ra2ini, art, actors))
    assert generate.DEFAULT_OUT.read_text(encoding="utf-8") == expected
