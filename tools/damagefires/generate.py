"""Generate mods/ra2/rules/damage-fires.yaml from RA2's rules.ini and art.ini.

RA2 lights fires on a building at the art.ini DamageFireOffset0..N screen-pixel
positions once it drops below ConditionYellow (50%). Each fire becomes a
WithIdleOverlay shown under a heavy-damage condition granted alongside them
(only buildings with fires grant it, so none grants an unused condition).

Usage: python3 -m damagefires.generate [--rules RULES.ini] [--art ART.ini] [--out FILE]
(run from the tools/ directory; defaults to the base RA2 INI files and
mods/ra2/rules/damage-fires.yaml).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from garrison.generate import ART_FILE, pixel_to_wvec
from ra2data import ini

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "mods" / "ra2" / "rules" / "damage-fires.yaml"

HEADER = (
    "# DO NOT EDIT - generated by tools/damagefires/generate.py from rules.ini/art.ini.\n"
    "# Re-run the generator instead of changing this file by hand.\n"
)

CONDITION = "heavy-damage"
# rules.ini DamageFireTypes=FIRE01,FIRE02,FIRE03; RA2 picks one at random, we cycle them by fire index.
FIRE_IMAGES = ("largefire", "mediumfire", "smallfire")
FIRE_HEIGHT = 0  # WDist above the building's origin

ACTOR_LINE = re.compile(r"^([A-Za-z0-9_.-]+):", re.M)


def _parse_pixels(value: str):
    parts = value.split(",")
    if len(parts) != 2:
        return None
    try:
        return int(parts[0]), int(parts[1])
    except ValueError:
        return None


def load_fires(rules, art, actors) -> list:
    """(rules section, [pixel offsets]) for every mod actor whose art has damage fires, sorted by name.

    Offsets are read from DamageFireOffset0 up to the first missing index; malformed ones are skipped.
    """
    result = []
    for name, section in rules.items():
        if name.lower() not in actors:
            continue
        # RA2 reads keys case-insensitively: the original art.ini spells one "damageFireOffset1".
        keys = {k.lower(): v for k, v in section.items()}
        art_section = {k.lower(): v for k, v in art.get(keys.get("image", name), art.get(name, {})).items()}
        offsets = []
        i = 0
        while f"damagefireoffset{i}" in art_section:
            parsed = _parse_pixels(art_section[f"damagefireoffset{i}"])
            if parsed is not None:
                offsets.append(parsed)
            i += 1
        if offsets:
            result.append((name, offsets))
    return sorted(result)


def render(fires) -> str:
    out = [HEADER]
    for name, offsets in fires:
        out.append(
            f"\n{name.lower()}:\n"
            "\tGrantConditionOnDamageState@HEAVYDAMAGE:\n"
            f"\t\tCondition: {CONDITION}\n"
            # The engine's Heavy state starts below 50%, RA2's ConditionYellow.
            "\t\tValidDamageStates: Heavy, Critical\n"
        )
        for i, (px, py) in enumerate(offsets):
            x, y, _ = pixel_to_wvec(px, py)
            out.append(
                f"\tWithIdleOverlay@DAMAGEFIRE{i}:\n"
                f"\t\tRequiresCondition: {CONDITION}\n"
                f"\t\tImage: {FIRE_IMAGES[i % len(FIRE_IMAGES)]}\n"
                "\t\tSequence: idle\n"
                "\t\tPalette: effect\n"
                f"\t\tOffset: {x},{y},{FIRE_HEIGHT}\n"
            )
    return "".join(out)


def mod_actor_names(rules_dir, exclude=None) -> set:
    """Lower-cased top-level actor names in rules_dir/**/*.yaml, without ^templates or the exclude file."""
    names = set()
    for path in Path(rules_dir).rglob("*.yaml"):
        if exclude is not None and path.resolve() == Path(exclude).resolve():
            continue
        names.update(n.lower() for n in ACTOR_LINE.findall(path.read_text(encoding="utf-8-sig")))
    return names


def main(argv=None) -> int:
    folder = ini.ra2ini_dir()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rules", default=str(folder / ini.RULES_FILE) if folder else None)
    parser.add_argument("--art", default=str(folder / ART_FILE) if folder else None)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args(argv)
    if not args.rules or not args.art:
        print("original INI files not found; pass --rules/--art or set $RA2INI", file=sys.stderr)
        return 1
    out = Path(args.out)
    # Always skip the committed output, also when writing elsewhere: its actors are not a source.
    actors = mod_actor_names(DEFAULT_OUT.parent, exclude=DEFAULT_OUT)
    text = render(load_fires(ini.parse_ini(args.rules), ini.parse_ini(args.art), actors))
    out.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
